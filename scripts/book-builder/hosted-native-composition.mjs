import assert from "node:assert/strict";
import { expect } from "@playwright/test";
import { authorHostedSharedCanvas, reviewHostedComposition } from "./hosted-native-shared-canvas.mjs";
import sharp from "sharp";
import { normalizeNativeRuntimePublicDocument, normalizeNativeRuntimeTeacherDocument } from "../../src/data/native-activities/nativeActivityRuntimeValidation.js";
import { exerciseHostedFlowBank } from './hosted-flow-bank-acceptance.mjs';

export async function exerciseHostedComposition(page, { nativeDocuments, nativeAssets, imageId, answerBytes, output }) {
  const save = async (root) => { const response = page.waitForResponse((value) => value.request().method() === "POST" && value.url().endsWith("/save")); await root.getByRole("button", { name: "Save Draft", exact: true }).click(); assert.equal((await response).status(), 200); };
  await page.goto(`${new URL(page.url()).origin}/#/books/ultimate-b2/components/ultimate-b2-students-book/activities`, { waitUntil: "domcontentloaded" });
  await page.getByRole("button", { name: "Add Activity", exact: true }).click();
  await page.getByRole("radio", { name: /Multi-Part/ }).check();
  await page.getByLabel(/Initial title/).fill("Synthetic composed activity");
  await page.getByRole("button", { name: "Create activity", exact: true }).click();
  const editor = page.locator(".native-multi-part-editor");
  await expect(editor).toBeVisible();
  const id = [...nativeDocuments].find(([, pair]) => pair.publicDocument.metadata.title === "Synthetic composed activity")[0];
  const initialCount = nativeDocuments.size;
  const writes = []; const reads = [];
  const capture = (request) => { if (request.url().includes("/native-activity-")) reads.push(request.url()); if (request.method() === "POST" && request.url().endsWith("/save")) writes.push(request.postDataJSON()); };
  page.on("request", capture);
  await editor.getByRole("button", { name: "Add flow panel", exact: true }).click();
  await editor.getByLabel("Section type", { exact: true }).selectOption("single-choice");
  for (const [name, prompt] of [["First choices", "Which first?"], ["Second choices", "Which second?"]]) {
    await editor.getByRole("button", { name: "Add Section", exact: true }).click();
    await editor.getByLabel("Section title", { exact: true }).fill(name);
    const child = editor.locator(".native-single-choice-editor:visible");
    await child.getByRole("button", { name: "Add Question", exact: true }).click();
    await child.getByLabel("Prompt", { exact: true }).fill(prompt);
    await child.getByLabel("Option 1", { exact: true }).fill("Yes");
    await child.getByLabel("Option 2", { exact: true }).fill("No");
    await child.getByRole("tab", { name: "Answer Key", exact: true }).click();
    await child.getByRole("checkbox", { name: "Option 1: Yes", exact: true }).check();
    await expect(child.getByRole("button", { name: "Save Draft", exact: true })).toHaveCount(0);
  }
  await save(editor);
  await expect(editor.getByRole("button", { name: "Save Draft", exact: true })).toBeDisabled();
  assert.equal(writes.length, 1); assert.equal(nativeDocuments.size, initialCount); assert.equal(reads.length, 0);
  const saved = structuredClone(nativeDocuments.get(id));
  assert.equal(saved.publicDocument.parts[0].interaction.sections.length, 2);
  const publicDocument = normalizeNativeRuntimePublicDocument(saved.publicDocument, { activityId: id, kind: "multi-part" });
  normalizeNativeRuntimeTeacherDocument(saved.teacherDocument, { activityId: id, kind: "multi-part", publicDocument });
  await editor.getByRole("tab", { name: "Preview whole activity", exact: true }).click();
  await editor.getByRole("radio", { name: "Yes", exact: true }).first().check();
  await editor.getByRole("radio", { name: "No", exact: true }).last().check();
  await expect(editor.getByRole("radio", { name: "Yes", exact: true }).first()).toBeChecked();
  await editor.getByRole("checkbox", { name: "Teacher preview", exact: true }).check();
  await editor.getByRole("button", { name: "Show next", exact: true }).click();
  await page.reload({ waitUntil: "domcontentloaded" });
  await page.getByRole("button", { name: new RegExp(id) }).click();
  await expect(editor.getByRole("button", { name: "First choices", exact: true })).toBeVisible();
  assert.deepEqual(nativeDocuments.get(id), saved);
  await editor.getByRole("button", { name: "Second choices", exact: true }).click();
  const bulk = editor.locator(".native-single-choice-editor:visible .native-bulk-generator");
  await bulk.locator("summary").click();
  await bulk.getByLabel("Paste numbered Multiple Choice content", { exact: true }).fill("1. Rebuilt second section\n*Yes\n*No");
  await bulk.getByRole("checkbox", { name: /Replace existing semantic content/ }).check();
  await bulk.getByRole("button", { name: "Generate content", exact: true }).click(); await save(editor);
  assert.deepEqual(nativeDocuments.get(id).publicDocument.parts[0].interaction.sections[0], saved.publicDocument.parts[0].interaction.sections[0]);
  assert.deepEqual(nativeDocuments.get(id).teacherDocument.parts[0].solution.sections[0], saved.teacherDocument.parts[0].solution.sections[0]);
  assert.equal(nativeDocuments.get(id).publicDocument.parts[0].interaction.sections[1].interaction.questions[0].selectionMode, "multiple");
  await authorHostedSharedCanvas(page, editor); await save(editor);
  const composed = nativeDocuments.get(id);
  assert.equal(composed.publicDocument.parts[0].interaction.panels.length, 2);
  assert.equal(composed.publicDocument.parts[0].interaction.sections.length, 4);
  assert.equal(nativeDocuments.size, initialCount);
  const normalized = normalizeNativeRuntimePublicDocument(composed.publicDocument, { activityId: id, kind: "multi-part" });
  normalizeNativeRuntimeTeacherDocument(composed.teacherDocument, { activityId: id, kind: "multi-part", publicDocument: normalized });
  page.off("request", capture);
  await reviewHostedComposition(page, id);
  await page.getByRole("button", { name: new RegExp(imageId) }).click();
  const image = page.locator(".native-image-editor:visible");
  await image.getByRole("tab", { name: "Content", exact: true }).click();
  await image.getByLabel("Enable Sample answer", { exact: true }).check();
  await image.getByLabel("Sample answer image", { exact: true }).setInputFiles({ name: "choice-private-answer.png", mimeType: "image/png", buffer: answerBytes });
  await expect(image.getByText("Protected image uploaded. Save Draft to retain it.", { exact: true })).toBeVisible();
  await image.getByLabel("Sample answer description", { exact: true }).fill("Synthetic private Teacher answer");
  await save(image);
  await expect(image.getByRole("button", { name: "Save Draft", exact: true })).toBeDisabled();
  const protectedPair = nativeDocuments.get(imageId);
  assert.equal(protectedPair.teacherDocument.parts[0].solution.sampleAnswer.image.reference.role, "native_teacher_answer");
  assert.doesNotMatch(JSON.stringify(protectedPair.publicDocument), /Synthetic private Teacher answer|native_teacher_answer/);
  await page.reload({ waitUntil: "domcontentloaded" }); await page.getByRole("button", { name: new RegExp(imageId) }).click();
  await expect(image.getByLabel("Enable Sample answer", { exact: true })).toBeChecked();
  await expect(image.getByLabel("Sample answer description", { exact: true })).toHaveValue("Synthetic private Teacher answer");
  const originalAnswer = structuredClone(nativeDocuments.get(imageId).teacherDocument.parts[0].solution.sampleAnswer);
  const replacement = await sharp({ create: { width: 600, height: 1800, channels: 3, background: "#cef4de" } }).png().toBuffer();
  let releasePrepare;
  const barrier = new Promise((resolve) => { releasePrepare = resolve; });
  const failPrepare = async (route) => { await barrier; return route.fulfill({ status: 503, contentType: "application/json", body: '{"error":"synthetic_upload_failure"}' }); };
  await page.route("**/assets/prepare", failPrepare);
  await image.getByLabel("Sample answer image", { exact: true }).setInputFiles({ name: "choice-private-replacement.png", mimeType: "image/png", buffer: replacement });
  await expect(image.getByRole("button", { name: "Save Draft", exact: true })).toBeDisabled();
  releasePrepare(); await expect(image.getByText("Protected image upload failed. The previous answer is preserved.", { exact: true })).toBeVisible();
  assert.deepEqual(nativeDocuments.get(imageId).teacherDocument.parts[0].solution.sampleAnswer, originalAnswer);
  await page.unroute("**/assets/prepare", failPrepare);
  await image.getByLabel("Sample answer image", { exact: true }).setInputFiles({ name: "choice-private-replacement.png", mimeType: "image/png", buffer: replacement });
  await expect(image.getByText("Protected image uploaded. Save Draft to retain it.", { exact: true })).toBeVisible(); await save(image);
  assert.notEqual(nativeDocuments.get(imageId).teacherDocument.parts[0].solution.sampleAnswer.image.reference.assetId, originalAnswer.image.reference.assetId);
  await image.getByRole("button", { name: "Remove Sample answer image", exact: true }).click(); await save(image);
  await page.reload({ waitUntil: "domcontentloaded" }); await page.getByRole("button", { name: new RegExp(imageId) }).click();
  assert.deepEqual(nativeDocuments.get(imageId).teacherDocument.parts[0].solution.sampleAnswer, { enabled: true, image: null });
  await expect(image.getByText("Upload an answer image before publication.", { exact: true })).toBeVisible();
  await exerciseHostedFlowBank(page, {nativeDocuments,nativeAssets,output});
}
